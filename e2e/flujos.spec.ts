test("una relación mecánica nueva distingue el peso original de la estimación", async ({ page }) => {
  await page.getByRole("button", { name: "Empezar Tren superior", exact: true }).click()
  await page.getByRole("link", { name: /Remo sentado/ }).click()
  await page.getByRole("button", { name: "Agregar implemento", exact: true }).click()
  await page.getByRole("textbox", { name: "Tipo", exact: true }).fill("Máquina de remo")
  await page.getByRole("textbox", { name: "Marca", exact: true }).fill("Prueba")
  await page.getByRole("textbox", { name: "Modelo", exact: true }).fill("X-1")
  await page.getByRole("textbox", { name: "Relación mecánica", exact: true }).fill("2")
  await page.getByRole("button", { name: "Guardar implemento", exact: true }).click()
  await expect(page.getByText("Implemento guardado")).toBeVisible()
  await expect(page.getByRole("combobox", { name: "Implemento" })).toContainText("X-1")
  await expect(page.getByText("Relación mecánica: 2")).toBeVisible()
  await expect(page.getByRole("textbox", { name: "Peso serie 1" })).toHaveValue("")
  await page.getByRole("textbox", { name: "Peso serie 1" }).fill("10")
  await page.getByRole("textbox", { name: "Repeticiones serie 1" }).fill("8")
  await page.getByRole("button", { name: "Confirmar serie 1", exact: true }).click()
  await page.getByRole("link", { name: "Volver a ejercicios" }).click()
  await page.getByRole("button", { name: "Terminar entrenamiento", exact: true }).click()
  await page.getByRole("button", { name: "Terminar", exact: true }).click()
  await page.getByRole("link", { name: "Progreso" }).click()
  const detail = page.getByRole("region", { name: "Detalle del registro de Remo sentado" })
  await expect(detail).toContainText("Peso registrado: 10 kg")
  await expect(detail).toContainText("Estimado")
  await expect(detail).toContainText("Carga estimada: 20 kg")
})
