import { expect, type Page, test } from "@playwright/test"

async function resetDemo(page: Page) {
  await page.goto("/")
  await page.getByRole("button", { name: "Restablecer datos", exact: true }).click()
  await page.getByRole("button", { name: "Restablecer", exact: true }).click()
  await expect(page.getByText("Datos de demostración restablecidos")).toBeVisible()
}

async function openSerie(page: Page, series: number) {
  const weight = page.getByRole("textbox", { name: `Peso serie ${series}` })
  if (await weight.isVisible()) return
  await page.getByRole("button", { name: new RegExp(`^Serie ${series}\\b`) }).click()
  await expect(weight).toBeVisible()
}

async function noHorizontalOverflow(page: Page) {
  const overflows = await page.evaluate(
    () => document.documentElement.scrollWidth > document.documentElement.clientWidth + 1,
  )
  expect(overflows).toBe(false)
}

test.beforeEach(async ({ page }) => {
  await resetDemo(page)
})

test("registra una sesión, la corrige y persiste al recargar", async ({ page }) => {
  await expect(page.getByText("Sugerida hoy")).toBeVisible()
  await page.getByRole("button", { name: "Empezar Tren superior", exact: true }).click()
  await page.getByRole("link", { name: /Remo sentado/ }).click()
  await expect(page.getByRole("textbox", { name: "Peso serie 1" })).toHaveValue("50")
  await page.getByRole("textbox", { name: "Peso serie 1" }).fill("60")
  await page.getByRole("textbox", { name: "Repeticiones serie 1" }).fill("6")
  await page.getByRole("button", { name: "Confirmar serie 1", exact: true }).click()
  await expect(page.getByText("Serie guardada")).toBeVisible()
  await page.reload()
  await openSerie(page, 1)
  await expect(page.getByRole("textbox", { name: "Peso serie 1" })).toHaveValue("60")
  await page.getByRole("button", { name: "Subir repeticiones de la serie 1" }).click()
  await page.getByRole("button", { name: "Guardar cambios de la serie 1", exact: true }).click()
  await expect(page.getByText("Serie actualizada")).toBeVisible()
  await page.reload()
  await openSerie(page, 1)
  await expect(page.getByRole("textbox", { name: "Repeticiones serie 1" })).toHaveValue("7")
  await page.getByRole("link", { name: "Volver a ejercicios" }).click()
  await page.getByRole("button", { name: "Terminar entrenamiento", exact: true }).click()
  await page.getByRole("button", { name: "Terminar", exact: true }).click()
  await expect(page.getByText("Entrenamiento terminado")).toBeVisible()
  await page.reload()
  await expect(page.getByText("60 kg × 7")).toBeVisible()
  await noHorizontalOverflow(page)
})

test("el gimnasio activo prioriza su historial y separa los otros", async ({ page }) => {
  await page.getByRole("radio", { name: "Sala Sur", exact: true }).click()
  await expect(page.getByText("Gimnasio activo: Sala Sur")).toBeVisible()
  await page.getByRole("link", { name: "Historial" }).click()
  await expect(page.getByRole("region", { name: "En Sala Sur" })).toContainText("90 lb")
  await expect(page.getByRole("region", { name: "Otros gimnasios" })).toContainText("Gimnasio Norte")
  await expect(page.getByRole("region", { name: "Otros gimnasios" })).toContainText("55 kg")
  await expect(page.locator("[data-gym-scope='other']").first()).toHaveClass(/text-muted-foreground/)
  await expect(page.locator("[data-gym-scope='current']").first()).not.toHaveClass(/text-muted-foreground/)
  await page.getByRole("link", { name: "Inicio" }).click()
  await page.getByRole("button", { name: "Empezar Tren superior", exact: true }).click()
  await page.getByRole("link", { name: /Remo sentado/ }).click()
  await expect(page.getByRole("combobox", { name: "Implemento" })).toContainText("LM-4")
  await expect(page.getByRole("textbox", { name: "Peso serie 1" })).toHaveValue("90")
  await expect(page.getByText("Relación mecánica: 0,5")).toBeVisible()
  const same = page.getByRole("region", { name: "Con este implemento" })
  const others = page.getByRole("region", { name: "Otros gimnasios" })
  await expect(same).toContainText("90 lb")
  await expect(same).not.toContainText("55 kg")
  await expect(others).toContainText("55 kg")
  await expect(others).toContainText("Gimnasio Norte")
  await expect(others.getByText("Otro gimnasio").first()).toBeVisible()
  await noHorizontalOverflow(page)
})

test("un cambio temporal no modifica la rutina original", async ({ page }) => {
  await page.getByRole("button", { name: "Empezar Tren superior", exact: true }).click()
  await page.getByRole("link", { name: /Remo sentado/ }).click()
  await page.getByRole("button", { name: "Cambiar", exact: true }).click()
  await expect(page.getByText("La rutina original no se modifica.")).toBeVisible()
  await page.getByRole("button", { name: "Remo con mancuerna", exact: true }).click()
  await expect(page.getByRole("heading", { level: 1, name: "Remo con mancuerna" })).toBeVisible()
  await expect(page.getByText("En la rutina: Remo sentado", { exact: true })).toBeVisible()
  await expect(page.getByRole("region", { name: "Notas" })).toContainText("Máquina ocupada")
  await page.reload()
  await expect(page.getByRole("heading", { level: 1, name: "Remo con mancuerna" })).toBeVisible()
  await expect(page.getByRole("textbox", { name: "Peso serie 1" })).toHaveValue("22")
  await expect(page.getByRole("combobox", { name: "Implemento" })).toContainText("Hex")
  await page.getByRole("button", { name: "Confirmar serie 1", exact: true }).click()
  await expect(page.getByText("Serie guardada")).toBeVisible()
  await page.getByRole("link", { name: "Inicio" }).click()
  await expect(page.getByRole("list", { name: "Ejercicios de Tren superior" }).getByRole("listitem")).toHaveText([
    "Press inclinado en máquina",
    "Remo sentado",
    "Jalón al pecho",
  ])
  await page.getByRole("link", { name: "Continuar sesión", exact: true }).click()
  await page.getByRole("button", { name: "Terminar entrenamiento", exact: true }).click()
  await page.getByRole("button", { name: "Terminar", exact: true }).click()
  await page.getByRole("link", { name: "Inicio" }).click()
  await page.getByRole("button", { name: "Empezar Tren superior", exact: true }).click()
  await page.getByRole("link", { name: /Remo sentado/ }).click()
  await expect(page.getByRole("heading", { level: 1, name: "Remo sentado" })).toBeVisible()
  await expect(page.getByText("En la rutina:")).toHaveCount(0)
})

